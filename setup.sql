-- 2) Identidad email/password (necesaria para iniciar sesión).
--    Se adapta a versiones antiguas y nuevas del esquema de Auth.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'auth' AND table_name = 'identities' AND column_name = 'email'
    ) THEN
        INSERT INTO auth.identities (
            provider_id, user_id, identity_data, provider, email,
            last_sign_in_at, created_at, updated_at
        )
        SELECT
            u.id::text,
            u.id,
            jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true),
            'email',
            u.email,
            now(), now(), now()
        FROM auth.users u
        WHERE u.email = 'cehg@aunar.com'
        ON CONFLICT (provider_id, provider) DO NOTHING;
    ELSE
        INSERT INTO auth.identities (
            provider_id, user_id, identity_data, provider,
            last_sign_in_at, created_at, updated_at
        )
        SELECT
            u.id::text,
            u.id,
            jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true),
            'email',
            now(), now(), now()
        FROM auth.users u
        WHERE u.email = 'cehg@aunar.com'
        ON CONFLICT (provider_id, provider) DO NOTHING;
    END IF;
END $$;

-- 3) Tabla del catálogo de la biblioteca.
CREATE TABLE IF NOT EXISTS public.libros (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo      text NOT NULL,
    autor       text NOT NULL,
    categoria   text NOT NULL DEFAULT 'General',
    descripcion text NOT NULL DEFAULT '',
    anio        integer,
    creado_en   timestamptz NOT NULL DEFAULT now()
);

-- 4) Seguridad: lectura pública, escritura solo desde el panel.
ALTER TABLE public.libros ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lectura publica de libros" ON public.libros;
CREATE POLICY "Lectura publica de libros"
    ON public.libros FOR SELECT
    TO anon, authenticated
    USING (true);

GRANT SELECT ON public.libros TO anon, authenticated;

